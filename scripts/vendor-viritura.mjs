import { execFileSync } from "node:child_process";
import { copyFile, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const checkout = resolve(process.argv[2] ?? "../viritura");
const outDir = fileURLToPath(new URL("../src/lib/viritura/", import.meta.url));
const packages = join(checkout, "packages");

const git = (...args) =>
  execFileSync("git", ["-C", checkout, ...args], { encoding: "utf8" }).trim();

if (git("status", "--porcelain", "--", "packages")) {
  throw new Error(`${checkout}/packages has uncommitted changes.`);
}

const entryDir = await mkdtemp(join(tmpdir(), "vendor-viritura-"));
const entry = join(entryDir, "entry.js");
await writeFile(
  entry,
  `
export { convertMusicXmlToMnx, convertMxlToMnx, DiagnosticCollector } from "${packages}/musicxml/src/index.ts";
export { readJsonFromYDoc, syncJsonToYDoc } from "${packages}/crdt/src/yProjection/index.ts";
export { generateRoomId } from "${packages}/crdt/src/roomId.ts";
`,
);

await build({
  configFile: false,
  publicDir: false,
  build: {
    outDir,
    emptyOutDir: false,
    minify: false,
    lib: { entry, formats: ["es"], fileName: () => "index.js" },
    rollupOptions: {
      external: ["yjs", "jszip", "@xmldom/xmldom"],
      output: {
        banner: `// @ts-nocheck\n// Generated by scripts/vendor-viritura.mjs from Viritura ${git("rev-parse", "HEAD")}.`,
      },
    },
  },
});
await rm(entryDir, { recursive: true });
await copyFile(join(checkout, "LICENSE"), join(outDir, "LICENSE"));
